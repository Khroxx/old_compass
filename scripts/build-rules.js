#!/usr/bin/env node
// old-compass — writes every static rule file from hooks/instructions.js, so the
// agents without hooks always get the same text. Run after editing the rules:
//   npm run build
const fs = require('fs');
const path = require('path');
const { fullDoc } = require('../hooks/instructions');

const root = path.join(__dirname, '..');
const body = fullDoc();
const header = '<!-- Generated by scripts/build-rules.js from hooks/instructions.js. Do not edit by hand. -->';

const files = {
  'skills/compass/SKILL.md': `---
name: compass
description: >
  Old Compass mentor mode (persona Grandpa): a wise old programmer who finds bugs, lint and design
  problems, points at file:line, explains with everyday analogies, quizzes the
  user and makes them write the code themselves. Use when the user says
  "compass", "grandpa", "drunk grandpa", asks to learn, or wants mentoring instead of
  finished code. Persona: grandpa (default) or drunk. Code level: teach
  (default), pseudo, show, write.
argument-hint: "[drunk|sober] [teach|pseudo|show|write] [off]"
license: MIT
---

${header}

Mode switches are handled by the plugin hooks. If no hook context names the active mode, adopt the mode from the arguments ($ARGUMENTS), defaulting to grandpa + teach, and keep it for the session.

${body}
`,
  // Claude Code only: a plugin output style becomes part of the system prompt
  // on every request, which sticks better than hook context. force-for-plugin
  // turns it on without the user picking it; keep-coding-instructions keeps
  // Claude Code's own engineering rules next to Grandpa's.
  'output-styles/old-compass.md': `---
name: Old Compass
description: Wise old coding mentor. Points at file:line, explains with analogies, quizzes you, makes you write the code.
keep-coding-instructions: true
force-for-plugin: true
---

${header}

The plugin hooks tell you the active persona and code level for this project (default: grandpa + teach). If hook context says "OLD COMPASS OFF", ignore this style completely and behave as the default Claude Code assistant until it is switched back on.

${body}
`,
  'AGENTS.md': `${header}\n\n${body}\n`,
  '.github/copilot-instructions.md': `${header}\n\n${body}\n`,
  '.clinerules/old-compass.md': `${header}\n\n${body}\n`,
  '.windsurf/rules/old-compass.md': `---\ntrigger: always_on\n---\n\n${header}\n\n${body}\n`,
  '.cursor/rules/old-compass.mdc': `---\ndescription: Old Compass coding mentor mode\nalwaysApply: true\n---\n\n${header}\n\n${body}\n`,
};

for (const [rel, content] of Object.entries(files)) {
  const file = path.join(root, rel);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
  console.log('wrote', rel);
}
